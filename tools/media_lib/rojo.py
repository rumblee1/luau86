"""Write the on-disk Luau86 media format."""

import base64


def module(path, image):
    # Omit empty sectors and limit each base64 string to 12 KiB.
    entries = []
    start = 0
    data = bytearray()
    for offset in range(0, len(image), 512):
        sector = image[offset:offset + 512]
        if not any(sector) or len(data) >= 9 * 1024:
            if data:
                entries.append((start, base64.b64encode(data).decode("ascii")))
                data.clear()
            if not any(sector):
                continue
        if not data:
            start = offset
        data.extend(sector)
    if data:
        entries.append((start, base64.b64encode(data).decode("ascii")))
    lines = ["-- Generated by tools/media.py.", "return {", f"\tsize = {len(image)},", "\tchunks = {"]
    lines.extend(f'\t\t{{ {offset}, "{encoded}" }},' for offset, encoded in entries)
    lines.extend(["\t},", "}", ""])
    content = "\n".join(lines)
    if len(content) >= 200_000:
        raise ValueError(f"{path.name} is too large for a Roblox ModuleScript")
    path.write_text(content, encoding="ascii")


def disk_modules(folder, image):
    folder.mkdir()
    block_size = 96 * 1024
    parts = []
    for offset in range(0, len(image), block_size):
        block = image[offset : offset + block_size]
        if any(block):
            name = f"Part{len(parts):03}"
            module(folder / f"{name}.luau", block)
            parts.append((offset, name))
    index = ["-- Generated by tools/media.py.", f"return {{ size = {len(image)}, parts = {{"]
    index.extend(f'\t{{ {offset}, "{name}" }},' for offset, name in parts)
    index.extend(["} }", ""])
    (folder / "Index.luau").write_text("\n".join(index), encoding="ascii")
